CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS games (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  food INTEGER NOT NULL DEFAULT 240 CHECK (food >= 0),
  wood INTEGER NOT NULL DEFAULT 220 CHECK (wood >= 0),
  gold INTEGER NOT NULL DEFAULT 160 CHECK (gold >= 0),
  troops INTEGER NOT NULL DEFAULT 12 CHECK (troops >= 0),
  health INTEGER NOT NULL DEFAULT 100 CHECK (health BETWEEN 0 AND 100),
  farm INTEGER NOT NULL DEFAULT 1 CHECK (farm >= 0),
  lumber INTEGER NOT NULL DEFAULT 1 CHECK (lumber >= 0),
  barracks INTEGER NOT NULL DEFAULT 1 CHECK (barracks >= 0),
  castle INTEGER NOT NULL DEFAULT 1 CHECK (castle >= 0),
  victories INTEGER NOT NULL DEFAULT 0 CHECK (victories >= 0),
  updated_at TEXT NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
