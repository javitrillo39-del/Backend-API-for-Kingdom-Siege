ALTER TABLE player_profiles
  ADD COLUMN IF NOT EXISTS realm TEXT NOT NULL DEFAULT '07';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'player_profiles_realm_format'
      AND conrelid = 'player_profiles'::regclass
  ) THEN
    ALTER TABLE player_profiles
      ADD CONSTRAINT player_profiles_realm_format
      CHECK (realm ~ '^[0-9]{2}$');
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS chat_channels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_type TEXT NOT NULL CHECK (channel_type IN ('global', 'realm', 'private')),
  channel_key TEXT UNIQUE,
  realm TEXT,
  player_low_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  player_high_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (
    (channel_type = 'global'
      AND channel_key = 'global'
      AND realm IS NULL
      AND player_low_id IS NULL
      AND player_high_id IS NULL)
    OR
    (channel_type = 'realm'
      AND realm IS NOT NULL
      AND channel_key = 'realm:' || realm
      AND realm ~ '^[0-9]{2}$'
      AND player_low_id IS NULL
      AND player_high_id IS NULL)
    OR
    (channel_type = 'private'
      AND channel_key IS NULL
      AND realm IS NULL
      AND player_low_id IS NOT NULL
      AND player_high_id IS NOT NULL
      AND player_low_id < player_high_id)
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS chat_channels_private_pair_unique
  ON chat_channels(player_low_id, player_high_id)
  WHERE channel_type = 'private';

CREATE TABLE IF NOT EXISTS chat_channel_members (
  channel_id BIGINT NOT NULL REFERENCES chat_channels(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (channel_id, user_id)
);

CREATE INDEX IF NOT EXISTS chat_channel_members_user
  ON chat_channel_members(user_id, channel_id);

CREATE TABLE IF NOT EXISTS chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id BIGINT NOT NULL REFERENCES chat_channels(id) ON DELETE CASCADE,
  sender_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message_text TEXT NOT NULL
    CHECK (char_length(message_text) BETWEEN 1 AND 300)
    CHECK (message_text = btrim(message_text)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  edited_at TIMESTAMPTZ,
  deleted_at TIMESTAMPTZ,
  moderation_status TEXT NOT NULL DEFAULT 'visible'
    CHECK (moderation_status IN ('visible', 'reported', 'removed')),
  CHECK (edited_at IS NULL OR edited_at >= created_at)
);

CREATE INDEX IF NOT EXISTS chat_messages_channel_created
  ON chat_messages(channel_id, created_at DESC, id DESC)
  WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS chat_messages_sender_created
  ON chat_messages(sender_user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS message_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
  reporter_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reason TEXT NOT NULL CHECK (reason IN ('spam', 'harassment', 'inappropriate', 'other')),
  details TEXT NOT NULL DEFAULT '' CHECK (char_length(details) <= 300),
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'reviewed', 'dismissed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (message_id, reporter_user_id)
);

CREATE INDEX IF NOT EXISTS message_reports_status_created
  ON message_reports(status, created_at DESC);

CREATE TABLE IF NOT EXISTS muted_users (
  muter_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  muted_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (muter_user_id, muted_user_id),
  CHECK (muter_user_id <> muted_user_id)
);

CREATE INDEX IF NOT EXISTS muted_users_muted
  ON muted_users(muted_user_id, muter_user_id);

